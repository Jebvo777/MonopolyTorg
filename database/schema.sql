CREATE TABLE IF NOT EXISTS settings (
 name VARCHAR(100) PRIMARY KEY, value LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS admin_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, name VARCHAR(120) NOT NULL, active TINYINT NOT NULL DEFAULT 1,
 last_login DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS categories (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, parent_id INT UNSIGNED NULL,
 slug VARCHAR(190) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL, `lead` TEXT NOT NULL,
 description_html LONGTEXT NOT NULL, image VARCHAR(500) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1,
 seo_title VARCHAR(500) NOT NULL, seo_description TEXT NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_category_parent FOREIGN KEY(parent_id) REFERENCES categories(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id INT UNSIGNED NOT NULL,
 root_category VARCHAR(40) NOT NULL DEFAULT '', slug VARCHAR(190) NOT NULL UNIQUE,
 sku VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(500) NOT NULL,
 short_description TEXT NOT NULL, description_html LONGTEXT NOT NULL,
 specs_json LONGTEXT NOT NULL, gallery_json LONGTEXT NOT NULL,
 image VARCHAR(500) NOT NULL DEFAULT '', unit VARCHAR(20) NOT NULL DEFAULT 'шт.',
 request_hint TEXT NOT NULL, price DECIMAL(16,2) NULL, active TINYINT NOT NULL DEFAULT 1, featured TINYINT NOT NULL DEFAULT 0,
 sort_order INT NOT NULL DEFAULT 0, seo_title VARCHAR(600) NOT NULL, seo_description TEXT NOT NULL,
 old_urls_json LONGTEXT NOT NULL, source_file VARCHAR(500) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_product_category(category_id,active,sort_order), KEY idx_product_featured(active,featured,sort_order),
 CONSTRAINT fk_product_category FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pages (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(190) NOT NULL UNIQUE,
 title VARCHAR(500) NOT NULL, h1 VARCHAR(500) NOT NULL, `lead` TEXT NOT NULL, body_html LONGTEXT NOT NULL,
 image VARCHAR(500) NOT NULL DEFAULT '', template VARCHAR(40) NOT NULL DEFAULT 'content',
 seo_title VARCHAR(600) NOT NULL, seo_description TEXT NOT NULL,
 active TINYINT NOT NULL DEFAULT 1, sort_order INT NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS faqs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, question VARCHAR(500) NOT NULL,
 answer TEXT NOT NULL, sort_order INT NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS documents (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(500) NOT NULL,
 file_path VARCHAR(500) NOT NULL, kind VARCHAR(30) NOT NULL DEFAULT 'technical',
 description TEXT NOT NULL, sort_order INT NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS media (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, file_path VARCHAR(500) NOT NULL UNIQUE,
 original_name VARCHAR(255) NOT NULL, alt VARCHAR(500) NOT NULL DEFAULT '', mime VARCHAR(100) NOT NULL,
 bytes INT UNSIGNED NOT NULL DEFAULT 0, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS requests (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, public_id VARCHAR(40) NULL UNIQUE,
 idempotency_key CHAR(64) NOT NULL UNIQUE, type VARCHAR(30) NOT NULL,
 name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(40) NOT NULL,
 company VARCHAR(190) NOT NULL DEFAULT '', city VARCHAR(255) NOT NULL DEFAULT '', message TEXT NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'new', manager_note TEXT NOT NULL,
 email_status VARCHAR(30) NOT NULL DEFAULT 'queued', attachment_path VARCHAR(500) NULL,
 attachment_name VARCHAR(255) NULL, attachment_mime VARCHAR(100) NULL,
 attachment_bytes INT UNSIGNED NULL, ip_hash CHAR(64) NOT NULL,
 source VARCHAR(255) NOT NULL DEFAULT '', utm_source VARCHAR(100) NOT NULL DEFAULT '',
 consent_at DATETIME NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_request_created(created_at), KEY idx_request_status(status,created_at), KEY idx_request_ip(ip_hash,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS request_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, request_id INT UNSIGNED NOT NULL,
 product_id INT UNSIGNED NULL, name VARCHAR(500) NOT NULL, sku VARCHAR(80) NOT NULL DEFAULT '',
 quantity DECIMAL(16,3) NOT NULL, unit VARCHAR(20) NOT NULL, parameters TEXT NOT NULL,
 CONSTRAINT fk_item_request FOREIGN KEY(request_id) REFERENCES requests(id) ON DELETE CASCADE,
 CONSTRAINT fk_item_product FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE SET NULL,
 KEY idx_item_product(product_id,request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS email_outbox (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, request_id INT UNSIGNED NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'pending', attempts INT UNSIGNED NOT NULL DEFAULT 0,
 last_error TEXT NOT NULL, available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 locked_at DATETIME NULL, sent_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY idx_outbox_request(request_id), KEY idx_outbox_status(status,available_at),
 CONSTRAINT fk_outbox_request FOREIGN KEY(request_id) REFERENCES requests(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS visits (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, visitor_hash CHAR(64) NOT NULL,
 path VARCHAR(255) NOT NULL, product_id INT UNSIGNED NULL, referrer VARCHAR(190) NOT NULL DEFAULT '',
 device VARCHAR(20) NOT NULL, utm_source VARCHAR(100) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_visit_created(created_at), KEY idx_visit_product(product_id,created_at), KEY idx_visit_visitor(visitor_hash,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ip_hash CHAR(64) NOT NULL, success TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_login_ip(ip_hash,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL,
 action VARCHAR(100) NOT NULL, entity VARCHAR(80) NOT NULL, entity_id VARCHAR(100) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_audit_created(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
